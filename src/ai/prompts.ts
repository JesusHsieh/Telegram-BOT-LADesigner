export function getTaskPrompt(intent: LandscapeIntent, userInput: string, dataContext: string): string {
  const rule = taskRules[intent];
  return [
    `任務類型：/${intent}`,
    "",
    "使用者輸入：",
    userInput || "未提供補充內容",
    "",
    "可用資料上下文：",
    dataContext,
    "",
    "請依以下規則回覆：",
    rule,
    "",
    "最後請附上「下一步可輸入」並列出 2 到 4 個相關指令。"
  ].join("\n");
}

